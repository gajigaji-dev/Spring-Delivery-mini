-- Redis·Kafka 후속 개선 — docs/architecture.md Redis 장·Kafka 장
--   기존 결제·정산 행은 바꾸지 않음. 새 테이블 1개, notifications 발송 상태 컬럼, 조회·정리용 인덱스 추가

-- 1. DB 기반 결제 멱등성 기록
--    결제와 같은 트랜잭션에 저장 → Redis 기록이 사라지거나(TTL 만료·유실) Redis가 내려가 있어도
--    같은 Idempotency-Key 재시도에 처음 응답을 돌려줄 수 있음 (Redis 기록은 빠른 확인·동시 요청 차단용으로 계속 사용)
--    응답 본문은 저장하지 않음: 결제 직후 응답은 결제 행의 불변 값만으로 다시 만들 수 있음 (dto.PaymentResponse.atPayment)
CREATE TABLE payment_idempotency_keys (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id         bigint       NOT NULL,
    idempotency_key varchar(64)  NOT NULL,
    -- 요청 본문(orderId·paymentMethod)의 SHA-256 → 같은 키에 다른 요청이면 422
    fingerprint     varchar(64)  NOT NULL,
    payment_id      bigint       NOT NULL,
    created_at      timestamp(6) NOT NULL,
    CONSTRAINT payment_idempotency_keys_pkey PRIMARY KEY (id),
    -- 키는 사용자별로 구분 (다른 사용자가 같은 키를 써도 서로 영향 없음)
    CONSTRAINT uk_payment_idempotency_keys_user_key UNIQUE (user_id, idempotency_key),
    -- 결제 1건은 키 1개로만 만들어짐
    CONSTRAINT uk_payment_idempotency_keys_payment UNIQUE (payment_id),
    CONSTRAINT fk_payment_idempotency_keys_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_payment_idempotency_keys_payment FOREIGN KEY (payment_id) REFERENCES payments (id)
);

-- 보관 기간이 지난 기록 삭제용 (maintenance.RetentionCleaner)
CREATE INDEX idx_payment_idempotency_keys_created_at ON payment_idempotency_keys (created_at);

-- 2. Outbox 인덱스
-- FAILED 건수 메트릭·관리자 FAILED 목록 조회용 (FAILED는 드물어 인덱스가 작게 유지됨)
CREATE INDEX idx_outbox_events_failed ON outbox_events (id) WHERE status = 'FAILED';

-- 같은 주문의 앞 이벤트가 아직 발행 대기 중인지 확인하는 용도 (발행 순서 보장, OutboxEventRepository.findPublishableForUpdate)
CREATE INDEX idx_outbox_events_pending_aggregate ON outbox_events (aggregate_type, aggregate_id, id)
    WHERE status = 'PENDING';

-- 보관 기간이 지난 PUBLISHED 이벤트 삭제용
CREATE INDEX idx_outbox_events_published_at ON outbox_events (published_at) WHERE status = 'PUBLISHED';

-- 3. 보관 기간이 지난 Consumer 처리 기록 삭제용
CREATE INDEX idx_consumed_events_consumed_at ON consumed_events (consumed_at);

-- 4. 알림 발송 상태 — 알림 기록을 읽어 발송기(event.NotificationSender)로 보냄
--    PENDING : 발송 대기 (next_send_at 이후 발송 시도)
--    SENT    : 발송 완료
--    FAILED  : 재시도 한도 초과 — 자동 발송 대상에서 빠짐
--    SKIPPED : 발송 기능 도입 전에 저장된 기록 — 뒤늦게 발송되지 않도록 발송 대상에서 제외
--    기존 행은 SKIPPED로 채운 뒤 기본값을 없앰 → 새 행은 애플리케이션이 항상 값을 지정
ALTER TABLE notifications
    ADD COLUMN send_status        varchar(20)  NOT NULL DEFAULT 'SKIPPED',
    ADD COLUMN send_attempt_count integer      NOT NULL DEFAULT 0,
    ADD COLUMN next_send_at       timestamp(6),
    ADD COLUMN sent_at            timestamp(6),
    ADD COLUMN last_send_error    varchar(500);

UPDATE notifications SET next_send_at = created_at;

ALTER TABLE notifications
    ALTER COLUMN next_send_at SET NOT NULL,
    ALTER COLUMN send_status DROP DEFAULT,
    ALTER COLUMN send_attempt_count DROP DEFAULT,
    ADD CONSTRAINT notifications_send_status_check CHECK (send_status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    ADD CONSTRAINT notifications_send_attempt_count_check CHECK (send_attempt_count >= 0),
    -- 발송 완료 ⇔ 발송 시각 있음
    ADD CONSTRAINT notifications_sent_at_check CHECK ((send_status = 'SENT') = (sent_at IS NOT NULL));

-- 발송 대상 조회(PENDING이고 발송 시각이 지난 행, id 순)용 부분 인덱스
CREATE INDEX idx_notifications_send_pending ON notifications (next_send_at, id) WHERE send_status = 'PENDING';

-- 내 알림 목록 조회 (받는 사람별 id 순 페이징)
CREATE INDEX idx_notifications_recipient ON notifications (recipient_user_id, id);
