--   기존 회원은 로그인한 상태에서 직접 연결 (이메일 자동 매칭 없음 — users에 이메일이 없고, 공급자 이메일 확인 여부에 보안을 맡기지 않도록)
--   공급자 값에 CHECK를 두지 않음: 공급자 추가가 코드(social.SocialProvider 구현) + 설정만으로 끝나도록. 허용 값은 애플리케이션이 판단

-- 소셜 전용 회원은 비밀번호가 없음 (아이디·비밀번호 로그인 불가, UserService.login에서 거부)
-- 쓸 수 없는 무작위 해시를 넣는 대신 NULL: "비밀번호 없음"이 데이터로 드러나야 마지막 로그인 수단 해제를 막을 수 있음
ALTER TABLE users ALTER COLUMN password DROP NOT NULL;

CREATE TABLE social_accounts (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id           bigint       NOT NULL,
    provider          varchar(20)  NOT NULL,
    -- 공급자가 주는 회원 식별자 (카카오 회원번호, 구글 sub). 이메일·닉네임은 저장하지 않음 (로그인에 필요 없는 개인정보)
    provider_user_id  varchar(255) NOT NULL,
    created_at        timestamp(6),
    updated_at        timestamp(6),
    CONSTRAINT social_accounts_pkey PRIMARY KEY (id),
    CONSTRAINT fk_social_accounts_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- 같은 소셜 계정으로 중복 가입되지 않음 — 동시에 처음 로그인해도 DB가 최종으로 막음 (Service 사전 조회는 메시지용)
    CONSTRAINT uk_social_accounts_provider_user UNIQUE (provider, provider_user_id),
    -- 회원당 공급자별 1개 (카카오 계정 두 개를 한 회원에 연결하지 않음). 회원별 목록 조회 인덱스도 겸함
    CONSTRAINT uk_social_accounts_user_provider UNIQUE (user_id, provider)
);
