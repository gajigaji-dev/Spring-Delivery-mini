-- 주문 항목(OrderItem) 도입
--   주문 1건 : 항목 N개, 항목 1개 = 메뉴 1종 × 수량
--   주문 당시 메뉴 이름·단가를 항목에 복사해 저장 → 메뉴가 수정·삭제되어도 주문 내역은 그대로
--   orders.menu_id, orders.quantity는 항목으로 옮긴 뒤 제거

-- 1. 주문 항목 테이블
--    order_id: 주문이 지워지면 항목도 함께 삭제 (항목은 주문 없이 의미가 없음)
--    (order_id, menu_id) UNIQUE: 한 주문 안에서 같은 메뉴는 한 항목으로만 (수량으로 합침)
--      → 이 인덱스가 order_id로 시작하므로 주문별 항목 조회에 별도 인덱스 불필요
CREATE TABLE order_items (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    order_id   bigint      NOT NULL,
    menu_id    bigint      NOT NULL,
    menu_name  varchar(50) NOT NULL,
    unit_price bigint      NOT NULL,
    quantity   integer     NOT NULL,
    CONSTRAINT order_items_pkey PRIMARY KEY (id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_menu FOREIGN KEY (menu_id) REFERENCES menus (id),
    CONSTRAINT uk_order_items_order_menu UNIQUE (order_id, menu_id),
    CONSTRAINT order_items_quantity_check CHECK (quantity >= 1),
    CONSTRAINT order_items_unit_price_check CHECK (unit_price >= 0)
);

CREATE INDEX idx_order_items_menu_id ON order_items (menu_id);

-- 2. 기존 주문 백필 — 주문 1건당 항목 1개
--    단가: 현재 메뉴 가격이 아니라 total_price / quantity
--      → 주문 이후 메뉴 가격이 바뀌었어도 주문 당시 단가가 복원되고, 단가 × 수량 = 기존 총액이 유지됨
--    이름: 주문 당시 이름은 남아 있지 않으므로 현재 메뉴 이름으로 채움
INSERT INTO order_items (order_id, menu_id, menu_name, unit_price, quantity)
SELECT o.id, o.menu_id, m.name, o.total_price / o.quantity, o.quantity
FROM orders o
JOIN menus m ON m.id = o.menu_id
ORDER BY o.id;

-- 3. 항목으로 옮긴 컬럼 제거 (menu_id의 FK 제약도 함께 삭제됨)
ALTER TABLE orders DROP COLUMN menu_id;
ALTER TABLE orders DROP COLUMN quantity;
