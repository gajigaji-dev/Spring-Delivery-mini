-- 정산 감사 이력 + 집계 실패 기록 (#39) — docs/settlement-policy.md 10장
--   기존 테이블(settlements 등)은 바꾸지 않고 새 테이블 2개만 추가
--   기존 정산의 과거 전이는 처리자를 알 수 없으므로 이력을 만들어 넣지 않음 (V11 이후 전이부터 기록)

-- 1. 정산 상태 변경 이력 — 누가 언제 어떤 상태로 바꿨는지 (INSERT만, 수정·삭제 없음)
--    from_status NULL → PENDING : 집계로 정산이 만들어짐 (actor_user_id NULL = 스케줄러, 값 있음 = 수동 재집계한 관리자)
--    PENDING → CONFIRMED        : 관리자 확정
--    CONFIRMED → PAID           : 관리자 지급
CREATE TABLE settlement_status_histories (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    settlement_id bigint       NOT NULL,
    from_status   varchar(20),
    to_status     varchar(20)  NOT NULL,
    actor_user_id bigint,
    changed_at    timestamp(6) NOT NULL,
    CONSTRAINT settlement_status_histories_pkey PRIMARY KEY (id),
    CONSTRAINT fk_settlement_status_histories_settlement FOREIGN KEY (settlement_id) REFERENCES settlements (id),
    CONSTRAINT fk_settlement_status_histories_actor FOREIGN KEY (actor_user_id) REFERENCES users (id),

    -- 정산 1건은 각 상태에 한 번씩만 도달 → 같은 전이 이력이 두 번 저장되지 않음 (중복 지급 기록 방지)
    -- 이 제약이 만드는 (settlement_id, to_status) 인덱스로 정산별 이력 조회도 처리
    CONSTRAINT uk_settlement_status_histories_settlement_to UNIQUE (settlement_id, to_status),

    -- Settlement 엔티티가 허용하는 전이만 저장
    -- from_status가 NULL이면 비교 결과가 NULL(알 수 없음)이 되어 CHECK를 통과하므로 IS NOT NULL을 먼저 확인
    CONSTRAINT settlement_status_histories_transition_check CHECK (
        (from_status IS NULL AND to_status = 'PENDING')
        OR (from_status IS NOT NULL AND (
            (from_status = 'PENDING' AND to_status = 'CONFIRMED')
            OR (from_status = 'CONFIRMED' AND to_status = 'PAID')))),

    -- 확정·지급은 반드시 처리자(관리자)가 있어야 함 — 처리자 없는 이력은 스케줄러 집계뿐
    CONSTRAINT settlement_status_histories_actor_check CHECK (
        to_status = 'PENDING' OR actor_user_id IS NOT NULL)
);

-- 2. 정산 집계 실패 기록 — 매장·날짜당 1건, 실패할 때마다 같은 행을 갱신 (정산 금액과 무관한 운영 기록)
--    FAILED   : 집계가 오류로 롤백되어 정산이 없는 상태 → 스케줄러 재실행 또는 관리자 재집계 대상
--    RESOLVED : 이후 집계가 성공(정산 생성)했거나 집계할 대상이 없음을 확인함
--    last_failed_by_user_id / resolved_by_user_id NULL = 스케줄러, 값 있음 = 수동 재집계한 관리자
CREATE TABLE settlement_aggregation_failures (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,
    store_id               bigint       NOT NULL,
    settlement_date        date         NOT NULL,
    status                 varchar(20)  NOT NULL,
    failure_count          integer      NOT NULL,
    last_error             varchar(500) NOT NULL,
    first_failed_at        timestamp(6) NOT NULL,
    last_failed_at         timestamp(6) NOT NULL,
    last_failed_by_user_id bigint,
    resolved_at            timestamp(6),
    resolved_by_user_id    bigint,
    settlement_id          bigint,
    CONSTRAINT settlement_aggregation_failures_pkey PRIMARY KEY (id),
    CONSTRAINT fk_settlement_aggregation_failures_store FOREIGN KEY (store_id) REFERENCES stores (id),
    CONSTRAINT fk_settlement_aggregation_failures_failed_by FOREIGN KEY (last_failed_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_settlement_aggregation_failures_resolved_by FOREIGN KEY (resolved_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_settlement_aggregation_failures_settlement FOREIGN KEY (settlement_id) REFERENCES settlements (id),

    CONSTRAINT uk_settlement_aggregation_failures_store_date UNIQUE (store_id, settlement_date),
    CONSTRAINT settlement_aggregation_failures_status_check CHECK (status IN ('FAILED', 'RESOLVED')),
    CONSTRAINT settlement_aggregation_failures_count_check CHECK (failure_count >= 1),

    -- 해결 상태 ⇔ 해결 시각 있음
    CONSTRAINT settlement_aggregation_failures_resolved_at_check CHECK (
        (status = 'RESOLVED') = (resolved_at IS NOT NULL)),

    -- 아직 실패 상태인 기록에는 해결 정보(처리자·정산)가 없음
    CONSTRAINT settlement_aggregation_failures_resolved_info_check CHECK (
        status = 'RESOLVED' OR (resolved_by_user_id IS NULL AND settlement_id IS NULL))
);

-- 관리자가 미해결 실패만 조회 (대부분 RESOLVED로 끝나므로 부분 인덱스)
CREATE INDEX idx_settlement_aggregation_failures_failed
    ON settlement_aggregation_failures (settlement_date) WHERE status = 'FAILED';
