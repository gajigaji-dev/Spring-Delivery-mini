-- 부분 환불 (docs/settlement-policy.md 9장, docs/money-policy.md 부분 환불)
--   결제 1 : 환불 N (payment_refunds). 정산 차감 단위를 "환불된 결제"에서 "환불 1건"으로 바꿈
--   주문 1 : 결제 1(payments.order_id UNIQUE)은 그대로 → 중복 결제 방지 제약은 건드리지 않음
--   기존 결제·정산 행의 금액은 바꾸지 않음. 기존 전액 환불은 환불 1건으로 옮기고(백필), 차감 기록을 그 환불에 연결
SET LOCAL statement_timeout = 0; -- 백필이 데이터 양에 비례 — 운영 statement_timeout에 걸려 중간에 실패하지 않도록

-- 1. 결제: 누적 환불액·부분 환불 상태
ALTER TABLE payments ADD COLUMN refunded_amount bigint NOT NULL DEFAULT 0;
UPDATE payments SET refunded_amount = amount WHERE status = 'REFUNDED';

ALTER TABLE payments DROP CONSTRAINT payments_status_check;
ALTER TABLE payments ADD CONSTRAINT payments_status_check
    CHECK (status IN ('COMPLETED', 'CANCELLED', 'PARTIALLY_REFUNDED', 'REFUNDED'));
-- 상태와 누적 환불액이 항상 맞음 (환불 없음 0 / 부분 0 < x < 결제액 / 전액 = 결제액)
ALTER TABLE payments ADD CONSTRAINT payments_refunded_amount_check CHECK (
    (status IN ('COMPLETED', 'CANCELLED') AND refunded_amount = 0)
    OR (status = 'PARTIALLY_REFUNDED' AND refunded_amount > 0 AND refunded_amount < amount)
    OR (status = 'REFUNDED' AND refunded_amount = amount));

-- 미차감 환불 조회가 payment_refunds로 옮겨가 더 쓰지 않음 (V9)
DROP INDEX idx_payments_refunded_at;

-- 2. 환불 1건
CREATE TABLE payment_refunds (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    payment_id        bigint       NOT NULL,
    amount            bigint       NOT NULL,
    fee_amount        bigint       NOT NULL,
    settlement_amount bigint       NOT NULL,
    reason            varchar(200) NOT NULL,
    refunded_at       timestamp(6) NOT NULL,
    created_at        timestamp(6),
    updated_at        timestamp(6),
    CONSTRAINT payment_refunds_pkey PRIMARY KEY (id),
    CONSTRAINT fk_payment_refunds_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    -- 합계 비교는 numeric으로 올려 bigint 오버플로 없이 CHECK 위반으로 거부 (V3·V9와 같은 방식)
    CONSTRAINT payment_refunds_amount_check CHECK (
        amount > 0 AND fee_amount >= 0 AND settlement_amount >= 0
        AND fee_amount::numeric + settlement_amount::numeric = amount::numeric)
);
CREATE INDEX idx_payment_refunds_payment ON payment_refunds (payment_id, id);
-- 미차감 환불·기간별 환불 조회 (환불 시각 기준)
CREATE INDEX idx_payment_refunds_refunded_at ON payment_refunds (refunded_at);

-- 기존 전액 환불 = 환불 1건 (금액은 결제에 저장된 값 그대로 → 지금까지의 정산 차감액과 같음)
INSERT INTO payment_refunds (payment_id, amount, fee_amount, settlement_amount, reason, refunded_at, created_at, updated_at)
SELECT id, amount, fee_amount, settlement_amount, '전액 환불 (V21 이전 기록)', refunded_at, refunded_at, refunded_at
FROM payments
WHERE status = 'REFUNDED'
ORDER BY id;

-- 3. 정산 차감 기록: 결제 단위 → 환불 1건 단위
--    지금까지는 REFUNDED 결제마다 환불이 정확히 1건이라 payment_id로 1:1 연결됨
ALTER TABLE settlement_refunds ADD COLUMN payment_refund_id bigint;
UPDATE settlement_refunds sr
SET payment_refund_id = pr.id
FROM payment_refunds pr
WHERE pr.payment_id = sr.payment_id;
ALTER TABLE settlement_refunds ALTER COLUMN payment_refund_id SET NOT NULL;
ALTER TABLE settlement_refunds
    ADD CONSTRAINT fk_settlement_refunds_payment_refund FOREIGN KEY (payment_refund_id) REFERENCES payment_refunds (id),
    -- 환불 1건은 정확히 한 정산에서만 차감 (이전 uk_settlement_refunds_payment의 역할)
    ADD CONSTRAINT uk_settlement_refunds_payment_refund UNIQUE (payment_refund_id),
    -- 결제 1건의 부분 환불 여러 건이 각각 다른(또는 같은) 정산에서 차감될 수 있음
    DROP CONSTRAINT uk_settlement_refunds_payment;
-- payment_id FK 조회용 (UNIQUE 인덱스가 없어져서)
CREATE INDEX idx_settlement_refunds_payment ON settlement_refunds (payment_id);

-- 4. PG 취소 요청 ↔ 환불 1건 (pg_cancel_requests는 V20에서 생김)
ALTER TABLE pg_cancel_requests
    ADD CONSTRAINT fk_pg_cancel_requests_payment_refund FOREIGN KEY (payment_refund_id) REFERENCES payment_refunds (id);
