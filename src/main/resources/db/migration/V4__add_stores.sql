-- 매장(Store) 도입
--   점주(OWNER) 1명 : 매장 N개, 매장 1개 : 메뉴 N개, 매장 1개 : 주문 N개
--   메뉴의 주인은 menus.owner_id 대신 stores.owner_id로 판단 (같은 정보를 두 곳에 두지 않도록 owner_id 제거)
--   주문은 store_id를 직접 가짐 → 매장별 주문 조회·소유권 검증을 메뉴를 거치지 않고 처리

-- 1. 매장 테이블
CREATE TABLE stores (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    name       varchar(50)  NOT NULL,
    owner_id   bigint       NOT NULL,
    created_at timestamp(6),
    updated_at timestamp(6),
    CONSTRAINT stores_pkey PRIMARY KEY (id),
    CONSTRAINT fk_stores_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE INDEX idx_stores_owner_id ON stores (owner_id);

-- 2. 기존 데이터 백필 — 메뉴를 가진 점주마다 기본 매장 1개 생성
--    매장 이름은 "{아이디}의 매장" (users.username 최대 20자 + 4자 → 50자 이내)
--    created_at/updated_at은 NULL: 실제 생성 시각을 알 수 없음 (V2와 같은 정책, 신규 행은 JPA Auditing이 채움)
--    메뉴가 없는 점주는 매장 없이 두고, 필요하면 매장 생성 API로 직접 만듦
INSERT INTO stores (name, owner_id)
SELECT u.username || '의 매장', u.id
FROM users u
WHERE EXISTS (SELECT 1 FROM menus m WHERE m.owner_id = u.id)
ORDER BY u.id;

-- 3. menus.store_id — 점주의 기본 매장으로 연결
--    (이 시점에는 점주당 매장이 정확히 1개이므로 owner_id로 매장이 하나로 정해짐)
ALTER TABLE menus ADD COLUMN store_id bigint;

UPDATE menus m
SET store_id = s.id
FROM stores s
WHERE s.owner_id = m.owner_id;

ALTER TABLE menus ALTER COLUMN store_id SET NOT NULL;
ALTER TABLE menus ADD CONSTRAINT fk_menus_store FOREIGN KEY (store_id) REFERENCES stores (id);
CREATE INDEX idx_menus_store_id ON menus (store_id);

-- 메뉴 주인은 이제 stores.owner_id로 판단 → 중복 컬럼 제거 (FK 제약도 함께 삭제됨)
ALTER TABLE menus DROP COLUMN owner_id;

-- 4. orders.store_id — 주문한 메뉴의 매장으로 연결
ALTER TABLE orders ADD COLUMN store_id bigint;

UPDATE orders o
SET store_id = m.store_id
FROM menus m
WHERE m.id = o.menu_id;

ALTER TABLE orders ALTER COLUMN store_id SET NOT NULL;
ALTER TABLE orders ADD CONSTRAINT fk_orders_store FOREIGN KEY (store_id) REFERENCES stores (id);
CREATE INDEX idx_orders_store_id ON orders (store_id);
