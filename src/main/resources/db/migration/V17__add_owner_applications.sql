-- 사장님 전환 신청 (#70 승인제) — docs/api.md 사장님 전환 신청 장
--   가입은 모두 CUSTOMER로 하고, 사장님은 신청 → 관리자 승인으로만 OWNER가 됨
--   (이전에는 가입 요청의 role: OWNER만으로 확인 없이 매장·메뉴를 만들 수 있었음)
--   users에 상태 컬럼을 두지 않고 신청을 행으로 남김 → 거절 후 재신청, 누가 언제 처리했는지 이력 보존
--   기존 OWNER 계정은 그대로 (백필 없음)

CREATE TABLE owner_applications (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id          bigint       NOT NULL,
    business_name    varchar(50)  NOT NULL,
    status           varchar(20)  NOT NULL,
    reject_reason    varchar(255),
    requested_at     timestamp(6) NOT NULL,
    decided_at       timestamp(6),
    decided_by       bigint,
    created_at       timestamp(6),
    updated_at       timestamp(6),
    CONSTRAINT owner_applications_pkey PRIMARY KEY (id),
    CONSTRAINT fk_owner_applications_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_owner_applications_decided_by FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT owner_applications_status_check CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED')),
    -- 처리된 신청은 처리 시각·처리자가 반드시 있고, 대기 중이면 둘 다 없음
    CONSTRAINT owner_applications_decided_check CHECK (
        (status = 'REQUESTED' AND decided_at IS NULL AND decided_by IS NULL)
        OR (status <> 'REQUESTED' AND decided_at IS NOT NULL AND decided_by IS NOT NULL)),
    -- 거절 사유는 거절일 때만
    CONSTRAINT owner_applications_reject_reason_check CHECK (
        (status = 'REJECTED' AND reject_reason IS NOT NULL) OR (status <> 'REJECTED' AND reject_reason IS NULL))
);

-- 사용자당 대기 중 신청은 1건 — 동시에 두 번 신청해도 DB가 최종으로 막음 (Service 사전 검사는 메시지용)
CREATE UNIQUE INDEX uk_owner_applications_user_requested ON owner_applications (user_id) WHERE status = 'REQUESTED';

-- 관리자 목록: 상태별 id 오름차순 페이징
CREATE INDEX idx_owner_applications_status_id ON owner_applications (status, id);

-- 내 최근 신청 조회 (user_id 기준 id 내림차순 1건)
CREATE INDEX idx_owner_applications_user_id_id ON owner_applications (user_id, id);
