-- Flyway 도입 시점(ddl-auto: update로 운영되던 DB)의 스키마
-- 기존 DB: spring.flyway.baseline-on-migrate로 이 버전을 "이미 적용됨"으로 표시하고 건너뜀
-- 빈 DB:   이 파일부터 실행되어 기존 DB와 같은 스키마가 만들어짐
-- 제약조건 이름은 Hibernate가 자동 생성했던 이름을 그대로 유지
--   → 이후 마이그레이션에서 이름으로 제약을 지울 때(예: payments.order_id UNIQUE 제거) 어느 DB든 같은 이름으로 동작

CREATE TABLE users (
    id       bigint GENERATED BY DEFAULT AS IDENTITY,
    password varchar(255) NOT NULL,
    role     varchar(255) NOT NULL,
    username varchar(20)  NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT ukr43af9ap4edm43mmtq01oddj6 UNIQUE (username),
    CONSTRAINT users_role_check CHECK (role IN ('CUSTOMER', 'OWNER'))
);

CREATE TABLE menus (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    description varchar(255),
    name        varchar(50) NOT NULL,
    price       integer     NOT NULL,
    owner_id    bigint      NOT NULL,
    deleted     boolean     NOT NULL DEFAULT false,
    updated_at  timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at  timestamp,
    CONSTRAINT menus_pkey PRIMARY KEY (id),
    CONSTRAINT fk2t5w5akd7boquwyfkfkbv2a5e FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE orders (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    delivery_address varchar(255) NOT NULL,
    quantity         integer      NOT NULL,
    status           varchar(255) NOT NULL,
    total_price      integer      NOT NULL,
    menu_id          bigint       NOT NULL,
    user_id          bigint       NOT NULL,
    created_at       timestamp(6),
    updated_at       timestamp(6),
    CONSTRAINT orders_pkey PRIMARY KEY (id),
    CONSTRAINT fkmkjklkcop7gfy47xu3i7aod7w FOREIGN KEY (menu_id) REFERENCES menus (id),
    CONSTRAINT fk32ql8ubntj5uh44ph9659tiih FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE payments (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    amount         integer      NOT NULL,
    paid_at        timestamp(6) NOT NULL,
    payment_method varchar(255) NOT NULL,
    order_id       bigint       NOT NULL,
    CONSTRAINT payments_pkey PRIMARY KEY (id),
    CONSTRAINT uk8vo36cen604as7etdfwmyjsxt UNIQUE (order_id),
    CONSTRAINT fk81gagumt0r8y3rmudcgpbk42l FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT payments_payment_method_check CHECK (payment_method IN ('CARD'))
);
