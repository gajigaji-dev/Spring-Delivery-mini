-- Kafka Transactional Outbox + 알림 기록 (#42) — docs/architecture.md Kafka 장
--   기존 테이블·행은 바꾸지 않고 새 테이블 3개만 추가
--   세 테이블 모두 업무 테이블(orders·users 등)에 FK를 두지 않음
--     - 이벤트는 발생 시점의 값을 payload에 스냅샷으로 담은 독립 기록 → 원본 행이 지워져도 발행·수신 기록은 남아야 함
--     - FK가 있으면 주문·회원 삭제가 이벤트 기록에 막힘

-- 1. 발행 대기 이벤트 (Outbox) — 결제·환불·배달완료 트랜잭션 안에서 업무 데이터와 함께 INSERT
--    PENDING   : 발행 대기 (next_attempt_at 이후 Publisher가 발행 시도)
--    PUBLISHED : Kafka 발행 확인(acks=all)됨
--    FAILED    : 재시도 한도 초과 — 자동 발행 대상에서 빠짐, 운영자가 원인 확인 후 처리
CREATE TABLE outbox_events (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id        uuid         NOT NULL,
    aggregate_type  varchar(30)  NOT NULL,
    aggregate_id    bigint       NOT NULL,
    event_type      varchar(50)  NOT NULL,
    payload         text         NOT NULL,
    status          varchar(20)  NOT NULL,
    attempt_count   integer      NOT NULL,
    next_attempt_at timestamp(6) NOT NULL,
    last_error      varchar(500),
    created_at      timestamp(6) NOT NULL,
    published_at    timestamp(6),
    CONSTRAINT outbox_events_pkey PRIMARY KEY (id),
    -- Consumer 멱등성의 기준 값 → 이벤트마다 하나
    CONSTRAINT uk_outbox_events_event_id UNIQUE (event_id),
    CONSTRAINT outbox_events_status_check CHECK (status IN ('PENDING', 'PUBLISHED', 'FAILED')),
    CONSTRAINT outbox_events_event_type_check CHECK (
        event_type IN ('PAYMENT_COMPLETED', 'PAYMENT_REFUNDED', 'DELIVERY_COMPLETED')),
    CONSTRAINT outbox_events_attempt_count_check CHECK (attempt_count >= 0),
    -- 발행 완료 ⇔ 발행 시각 있음
    CONSTRAINT outbox_events_published_at_check CHECK ((status = 'PUBLISHED') = (published_at IS NOT NULL))
);

-- Publisher 조회(PENDING이고 재시도 시각이 지난 행, id 순)용 부분 인덱스
-- 발행이 끝난 행(대부분)은 인덱스에 들어가지 않아 테이블이 커져도 인덱스는 대기 건수만큼만 유지됨
CREATE INDEX idx_outbox_events_pending ON outbox_events (next_attempt_at, id) WHERE status = 'PENDING';

-- 2. Consumer가 처리한 이벤트 — event_id 기준 멱등성
--    알림 저장과 같은 트랜잭션에서 INSERT ... ON CONFLICT DO NOTHING → 이미 있으면 같은 이벤트를 다시 처리하지 않음
--    (Kafka는 최소 한 번 전달이라 재발행·리밸런싱으로 같은 메시지가 다시 올 수 있음)
CREATE TABLE consumed_events (
    event_id    uuid         NOT NULL,
    event_type  varchar(50)  NOT NULL,
    consumed_at timestamp(6) NOT NULL,
    CONSTRAINT consumed_events_pkey PRIMARY KEY (event_id)
);

-- 3. 알림 기록 — 실제 이메일·SMS·푸시 발송은 하지 않고 "누구에게 무엇을 알릴지"만 저장
CREATE TABLE notifications (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id          uuid         NOT NULL,
    event_type        varchar(50)  NOT NULL,
    recipient_user_id bigint       NOT NULL,
    order_id          bigint       NOT NULL,
    message           varchar(255) NOT NULL,
    created_at        timestamp(6) NOT NULL,
    CONSTRAINT notifications_pkey PRIMARY KEY (id),
    -- consumed_events가 1차 방어, 이 제약은 같은 이벤트로 같은 사람에게 두 번 저장되는 일을 DB에서 한 번 더 막음
    CONSTRAINT uk_notifications_event_recipient UNIQUE (event_id, recipient_user_id)
);
