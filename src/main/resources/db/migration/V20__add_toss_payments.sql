-- 토스페이먼츠 테스트 모드 결제 (docs/api.md 토스페이먼츠 결제 장, docs/database.md V20)
--   기존 결제 행은 바꾸지 않음: 새 컬럼은 모두 NULL 허용 → 기존 결제·모의 결제(POST /api/payments)는 NULL 그대로

-- 1. PG 승인 정보 — PG를 거친 결제만 네 값이 모두 있음 (모의 결제는 모두 NULL)
--    pg_payment_key: 토스가 결제마다 발급하는 키 (최대 200자). 같은 키의 승인 요청이 다시 와도 결제가 두 번 저장되지 않도록 UNIQUE
--    pg_order_id: 결제창에 넘긴 주문번호 (6~64자, 서버가 order-{주문 id}-{난수}로 발급) — 토스 쪽에서 결제를 찾을 때 사용
--    pg_approved_at: 토스 승인 시각(Asia/Seoul로 변환). paid_at은 지금처럼 서버가 결제를 기록한 시각(정산 기준)이라 따로 둠
ALTER TABLE payments
    ADD COLUMN pg_provider    varchar(20),
    ADD COLUMN pg_payment_key varchar(200),
    ADD COLUMN pg_order_id    varchar(64),
    ADD COLUMN pg_approved_at timestamp(6);

ALTER TABLE payments
    ADD CONSTRAINT uk_payments_pg_payment_key UNIQUE (pg_payment_key),
    ADD CONSTRAINT uk_payments_pg_order_id UNIQUE (pg_order_id),
    ADD CONSTRAINT ck_payments_pg_provider CHECK (pg_provider IS NULL OR pg_provider IN ('TOSS')),
    -- 네 값은 함께 있거나 함께 없음 → 키만 있고 공급자가 없는 등 반쪽 기록을 막음
    ADD CONSTRAINT ck_payments_pg_fields CHECK (
        (pg_provider IS NULL AND pg_payment_key IS NULL AND pg_order_id IS NULL AND pg_approved_at IS NULL)
        OR (pg_provider IS NOT NULL AND pg_payment_key IS NOT NULL AND pg_order_id IS NOT NULL AND pg_approved_at IS NOT NULL));

-- 2. PG 결제 취소 요청 — 주문 취소·관리자 환불(V21 부분 환불 포함)·승인 후 기록 실패(보상 취소) 때 토스 결제 취소 API를 호출할 대상
--    업무 상태(주문 취소·결제 CANCELLED/환불)는 DB에서 먼저 확정하고, 이 행을 같은 트랜잭션에 남김 (Outbox와 같은 방식)
--    → 커밋 후 바로 1회 시도, 실패·시간 초과는 주기 작업(service.PgCancelProcessor)이 백오프로 재시도
--    payment_refund_id: 관리자 환불 1건(V21 payment_refunds)에서 생긴 취소 — FK는 V21에서 추가 (테이블이 V21에 생김)
--    balance_after: 이 취소가 반영된 뒤 토스 결제에 남아야 할 잔액 → 결과를 모르는 시도 뒤 재시도 전에 토스 잔액과 비교해 중복 취소 방지
--    payment_id NULL 허용: 승인은 됐지만 결제 행을 만들지 못한 경우(주문이 그 사이 취소됨 등)의 보상 취소
CREATE TABLE pg_cancel_requests (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    payment_id        bigint,
    payment_refund_id bigint,
    pg_provider       varchar(20)  NOT NULL,
    payment_key       varchar(200) NOT NULL,
    amount            bigint       NOT NULL,
    balance_after     bigint       NOT NULL,
    reason            varchar(200) NOT NULL,
    status            varchar(20)  NOT NULL,
    attempts          integer      NOT NULL DEFAULT 0,
    next_attempt_at   timestamp(6) NOT NULL,
    last_error        varchar(500),
    requested_at      timestamp(6) NOT NULL,
    completed_at      timestamp(6),
    created_at        timestamp(6),
    updated_at        timestamp(6),
    CONSTRAINT pg_cancel_requests_pkey PRIMARY KEY (id),
    -- 환불 1건당 취소 요청 1건
    CONSTRAINT uk_pg_cancel_requests_payment_refund UNIQUE (payment_refund_id),
    CONSTRAINT fk_pg_cancel_requests_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    CONSTRAINT ck_pg_cancel_requests_status CHECK (status IN ('PENDING', 'DONE', 'FAILED')),
    CONSTRAINT ck_pg_cancel_requests_provider CHECK (pg_provider IN ('TOSS')),
    CONSTRAINT ck_pg_cancel_requests_amount CHECK (amount > 0 AND balance_after >= 0),
    CONSTRAINT ck_pg_cancel_requests_completed CHECK ((status = 'DONE') = (completed_at IS NOT NULL))
);

-- 환불 없는 전액 취소(주문 취소·보상 취소)는 결제 키당 1건 — 같은 결제의 전액 취소 요청이 두 번 쌓이지 않음
CREATE UNIQUE INDEX uk_pg_cancel_requests_full_cancel ON pg_cancel_requests (payment_key) WHERE payment_refund_id IS NULL;
-- 재시도 대상 조회용 (PENDING만 — 완료된 행이 쌓여도 인덱스가 작게 유지됨)
CREATE INDEX idx_pg_cancel_requests_pending ON pg_cancel_requests (next_attempt_at, id) WHERE status = 'PENDING';
-- 같은 결제의 앞 요청이 끝났는지 확인 (결제 하나의 취소는 순서대로 하나씩) — DONE이 아닌 행만
CREATE INDEX idx_pg_cancel_requests_open_by_key ON pg_cancel_requests (payment_key, id) WHERE status <> 'DONE';
-- FAILED 건수 메트릭·운영자 확인용
CREATE INDEX idx_pg_cancel_requests_failed ON pg_cancel_requests (id) WHERE status = 'FAILED';
