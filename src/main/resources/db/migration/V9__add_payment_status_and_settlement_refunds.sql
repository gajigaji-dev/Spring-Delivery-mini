-- 결제 취소·환불과 차기 정산 반영 (#30) — docs/settlement-policy.md 9장
--   - payments: 결제 상태(COMPLETED / CANCELLED / REFUNDED)와 취소·환불 시각
--   - settlements: 판매·환불·이월을 나눠 기록, settlement_amount는 실제 지급액(≥ 0)
--   - settlement_refunds: 환불 1건이 어느 정산에서 차감됐는지 (payment_id UNIQUE → 한 번만 차감)
--   - settlement_carryovers: 이월분이 어느 정산에서 차감됐는지 (from_settlement_id UNIQUE → 한 번만 차감)
--   기존 정산 행은 금액이 그대로 유지되도록 백필 (환불·이월 0, 판매 정산액 = 기존 settlement_amount)

-- ===== 1. payments: 결제 상태 =====
-- 기존 결제는 모두 완료된 결제
ALTER TABLE payments ADD COLUMN status varchar(20) NOT NULL DEFAULT 'COMPLETED';
ALTER TABLE payments ADD COLUMN cancelled_at timestamp(6);
ALTER TABLE payments ADD COLUMN refunded_at  timestamp(6);

ALTER TABLE payments ADD CONSTRAINT payments_status_check
    CHECK (status IN ('COMPLETED', 'CANCELLED', 'REFUNDED'));
-- 상태 ⇔ 시각: 취소된 결제만 취소 시각, 환불된 결제만 환불 시각이 있음
ALTER TABLE payments ADD CONSTRAINT payments_cancelled_at_check
    CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL));
ALTER TABLE payments ADD CONSTRAINT payments_refunded_at_check
    CHECK ((status = 'REFUNDED') = (refunded_at IS NOT NULL));

-- 정산 집계가 환불 결제를 찾을 때 사용 (환불 건만 담는 부분 인덱스)
CREATE INDEX idx_payments_refunded_at ON payments (refunded_at) WHERE status = 'REFUNDED';

-- ===== 2. settlements: 판매·환불·이월 분리 =====
-- payment_count, total_amount, total_fee는 그대로 "판매" 합계로 사용
ALTER TABLE settlements ADD COLUMN sales_settlement_amount  bigint;
ALTER TABLE settlements ADD COLUMN refund_count             integer NOT NULL DEFAULT 0;
ALTER TABLE settlements ADD COLUMN refund_amount            bigint  NOT NULL DEFAULT 0;
ALTER TABLE settlements ADD COLUMN refund_fee               bigint  NOT NULL DEFAULT 0;
ALTER TABLE settlements ADD COLUMN refund_settlement_amount bigint  NOT NULL DEFAULT 0;
ALTER TABLE settlements ADD COLUMN carried_in_amount        bigint  NOT NULL DEFAULT 0;
ALTER TABLE settlements ADD COLUMN carried_out_amount       bigint  NOT NULL DEFAULT 0;

-- 기존 정산은 환불·이월이 없으므로 판매 정산액 = 지급액
UPDATE settlements SET sales_settlement_amount = settlement_amount;
ALTER TABLE settlements ALTER COLUMN sales_settlement_amount SET NOT NULL;

-- 금액 규칙 — 합계 비교는 numeric으로 올려 bigint 오버플로 없이 CHECK 위반으로 거부 (V3, V7과 같은 방식)
ALTER TABLE settlements DROP CONSTRAINT settlements_amount_check;

-- 판매: 수수료 + 판매 정산액 = 판매 총액
ALTER TABLE settlements ADD CONSTRAINT settlements_sales_amount_check CHECK (
    payment_count >= 0
    AND total_fee >= 0
    AND sales_settlement_amount >= 0
    AND total_fee::numeric + sales_settlement_amount::numeric = total_amount::numeric);

-- 환불: 환불 수수료 + 환불 정산액 = 환불 총액
ALTER TABLE settlements ADD CONSTRAINT settlements_refund_amount_check CHECK (
    refund_count >= 0
    AND refund_fee >= 0
    AND refund_settlement_amount >= 0
    AND refund_fee::numeric + refund_settlement_amount::numeric = refund_amount::numeric);

-- 지급·이월: 지급액과 다음 이월액은 0 이상이고, 둘 중 하나는 반드시 0
ALTER TABLE settlements ADD CONSTRAINT settlements_payout_check CHECK (
    settlement_amount >= 0
    AND carried_in_amount >= 0
    AND carried_out_amount >= 0
    AND (settlement_amount = 0 OR carried_out_amount = 0));

-- 순액: 지급액 - 다음 이월액 = 판매 정산액 - 환불 정산액 - 이월받은 금액
ALTER TABLE settlements ADD CONSTRAINT settlements_net_amount_check CHECK (
    settlement_amount::numeric - carried_out_amount::numeric
        = sales_settlement_amount::numeric - refund_settlement_amount::numeric - carried_in_amount::numeric);

-- 아직 차감되지 않은 이월분을 매장별로 찾을 때 사용 (이월이 생긴 정산만 담는 부분 인덱스)
CREATE INDEX idx_settlements_store_carried_out ON settlements (store_id) WHERE carried_out_amount > 0;

-- ===== 3. settlement_refunds: 환불 차감 기록 =====
CREATE TABLE settlement_refunds (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    settlement_id     bigint NOT NULL,
    payment_id        bigint NOT NULL,
    amount            bigint NOT NULL,
    fee_amount        bigint NOT NULL,
    settlement_amount bigint NOT NULL,
    created_at        timestamp(6),
    updated_at        timestamp(6),
    CONSTRAINT settlement_refunds_pkey PRIMARY KEY (id),
    CONSTRAINT fk_settlement_refunds_settlement FOREIGN KEY (settlement_id) REFERENCES settlements (id),
    CONSTRAINT fk_settlement_refunds_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    -- 환불 1건은 정확히 한 정산에서만 차감 (중복 차감 방지의 최종 보장)
    CONSTRAINT uk_settlement_refunds_payment UNIQUE (payment_id),
    CONSTRAINT settlement_refunds_amount_check CHECK (
        fee_amount >= 0
        AND settlement_amount >= 0
        AND fee_amount::numeric + settlement_amount::numeric = amount::numeric)
);
CREATE INDEX idx_settlement_refunds_settlement ON settlement_refunds (settlement_id);

-- ===== 4. settlement_carryovers: 이월 차감 기록 =====
CREATE TABLE settlement_carryovers (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    from_settlement_id bigint NOT NULL,
    to_settlement_id   bigint NOT NULL,
    amount             bigint NOT NULL,
    created_at         timestamp(6),
    updated_at         timestamp(6),
    CONSTRAINT settlement_carryovers_pkey PRIMARY KEY (id),
    CONSTRAINT fk_settlement_carryovers_from FOREIGN KEY (from_settlement_id) REFERENCES settlements (id),
    CONSTRAINT fk_settlement_carryovers_to FOREIGN KEY (to_settlement_id) REFERENCES settlements (id),
    -- 한 정산의 이월분은 정확히 한 번만 차감
    CONSTRAINT uk_settlement_carryovers_from UNIQUE (from_settlement_id),
    CONSTRAINT settlement_carryovers_amount_check CHECK (amount > 0),
    CONSTRAINT settlement_carryovers_self_check CHECK (from_settlement_id <> to_settlement_id)
);
CREATE INDEX idx_settlement_carryovers_to ON settlement_carryovers (to_settlement_id);
