-- 일 정산 확정 기록 (settlements) — 정산 기준은 docs/settlement-policy.md
--   매장 1곳의 하루(배달완료 시각 기준 [D 00:00, D+1 00:00), Asia/Seoul) 정산 결과를 확정해 저장
--   SettlementScheduler가 매일 01:10에 확정 (D일은 D+1 01:00 이후 확정 가능)

CREATE TABLE settlements (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    store_id          bigint       NOT NULL,
    settlement_date   date         NOT NULL,
    payment_count     integer      NOT NULL,
    total_amount      bigint       NOT NULL,
    total_fee         bigint       NOT NULL,
    settlement_amount bigint       NOT NULL,
    status            varchar(20)  NOT NULL,
    confirmed_at      timestamp(6) NOT NULL,
    paid_at           timestamp(6),
    created_at        timestamp(6),
    updated_at        timestamp(6),
    CONSTRAINT settlements_pkey PRIMARY KEY (id),
    CONSTRAINT fk_settlements_store FOREIGN KEY (store_id) REFERENCES stores (id),

    -- 같은 매장·같은 날짜는 한 번만 확정 (스케줄러가 여러 번·여러 서버에서 동시에 돌아도 중복 저장 거부)
    -- UNIQUE 제약이 만드는 (store_id, settlement_date) 인덱스로 매장별 정산 조회도 처리
    CONSTRAINT uk_settlements_store_date UNIQUE (store_id, settlement_date),

    CONSTRAINT settlements_status_check CHECK (status IN ('CONFIRMED', 'PAID')),

    -- 지급완료 상태 ⇔ 지급 시각 있음
    CONSTRAINT settlements_paid_at_check CHECK ((status = 'PAID') = (paid_at IS NOT NULL)),

    -- 금액 규칙은 payments와 같음 (V3) — 합계 비교는 numeric으로 올려 bigint 오버플로 없이 CHECK 위반으로 거부
    CONSTRAINT settlements_amount_check CHECK (
        payment_count >= 0
        AND total_fee >= 0
        AND settlement_amount >= 0
        AND total_fee::numeric + settlement_amount::numeric = total_amount::numeric)
);
