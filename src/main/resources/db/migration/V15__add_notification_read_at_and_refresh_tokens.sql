-- 알림 읽음 처리 + Refresh Token (프론트엔드 연동 전 백엔드 4·6번) — docs/database.md, docs/architecture.md 인증 장
--   기존 행의 값은 바꾸지 않음: notifications에는 NULL 허용 컬럼만 추가(기존 알림은 안 읽음), 새 테이블 1개

-- 1. 알림 읽음 시각
--    NULL = 안 읽음. 기본값 없는 NULL 컬럼 추가라 테이블을 다시 쓰지 않음(메타데이터만 변경)
--    알림 내용·발송 상태와 별개로 이 컬럼만 바뀜 (NotificationRepository.markReadIfUnread의 조건부 UPDATE)
ALTER TABLE notifications ADD COLUMN read_at timestamp(6);

-- 안 읽은 알림 개수 조회(받는 사람별 read_at IS NULL)용 부분 인덱스
-- 읽은 알림(대부분)은 인덱스에 들어가지 않아 알림이 쌓여도 안 읽은 건수만큼만 유지됨
CREATE INDEX idx_notifications_recipient_unread ON notifications (recipient_user_id) WHERE read_at IS NULL;

-- 2. Refresh Token — 로그인 1번 = 계열(family) 1개, 재발급마다 같은 계열에 새 행을 넣고 이전 행은 폐기
--    token_hash : 원문이 아닌 SHA-256(hex) → DB가 유출돼도 저장된 값으로 재발급을 받을 수 없음
--    revoked_at·revoke_reason : 폐기 시각·사유 (둘 다 있거나 둘 다 없음)
--      ROTATED        : 재발급에 사용됨 → 같은 토큰이 다시 오면 탈취·재사용으로 보고 계열 전체 폐기
--      LOGOUT         : 로그아웃
--      REUSE_DETECTED : 같은 계열에서 재사용이 감지되어 함께 폐기됨
--    행은 UPDATE로 폐기 상태만 바뀌고 해시·만료 시각은 바뀌지 않음
CREATE TABLE refresh_tokens (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id       bigint       NOT NULL,
    token_hash    varchar(64)  NOT NULL,
    family_id     uuid         NOT NULL,
    created_at    timestamp(6) NOT NULL,
    expires_at    timestamp(6) NOT NULL,
    revoked_at    timestamp(6),
    revoke_reason varchar(20),
    CONSTRAINT refresh_tokens_pkey PRIMARY KEY (id),
    -- 조회 기준 값 + 같은 토큰이 두 번 저장되지 않음 (UNIQUE 인덱스가 조회 인덱스를 겸함)
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT refresh_tokens_expires_at_check CHECK (expires_at > created_at),
    CONSTRAINT refresh_tokens_revoke_reason_check CHECK (revoke_reason IN ('ROTATED', 'LOGOUT', 'REUSE_DETECTED')),
    CONSTRAINT refresh_tokens_revoked_check CHECK ((revoked_at IS NULL) = (revoke_reason IS NULL))
);

-- 계열 전체 폐기(재사용 감지·로그아웃) 때 아직 유효한 행만 찾는 부분 인덱스
CREATE INDEX idx_refresh_tokens_family_active ON refresh_tokens (family_id) WHERE revoked_at IS NULL;
